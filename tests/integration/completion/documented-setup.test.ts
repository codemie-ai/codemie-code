/**
 * Documented shell-completion setup - end-to-end CLI tests
 *
 * Follows docs/SHELL-COMPLETIONS.md the way a user would: the built CLI writes
 * `codemie completion <shell>` to a temp file that is moved to the documented
 * path in an isolated home, then a fresh shell with that home completes
 * `codemie <Tab>` and `codemie --<Tab>` from the installed file alone.
 */

import { describe, it, expect, beforeAll, afterAll } from 'vitest';
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { expectExit, realDir, runIsolatedCli } from '../../helpers/isolated-cli.js';
import { startZsh, type ZshSession } from '../../helpers/zsh-pty.js';

const VERSION = (JSON.parse(readFileSync(resolve('package.json'), 'utf-8')) as { version: string }).version;
// Grounding: top-level commands named by docs/SHELL-COMPLETIONS.md:39 plus `completion` (src/cli/program.ts:122).
const TOP_LEVEL = ['list', 'install', 'doctor', 'completion'];
const ROOT_OPTIONS = ['--version', '--help'];

const has = (shell: string): boolean => process.platform !== 'win32' && spawnSync(shell, ['--version']).status === 0;

/** Writes `codemie completion <shell>` to `<file>.tmp`, then moves it to `file`, as the docs do. */
function installCompletion(home: string, shell: 'zsh' | 'fish', file: string): string {
  mkdirSync(join(file, '..'), { recursive: true });
  const res = runIsolatedCli({ codemieHome: join(home, '.codemie'), userHome: home }, ['completion', shell], { cwd: home });
  expectExit(res, 0);
  writeFileSync(`${file}.tmp`, res.stdout);
  renameSync(`${file}.tmp`, file);
  expect(existsSync(`${file}.tmp`)).toBe(false);
  return readFileSync(file, 'utf-8');
}

for (const shell of ['zsh', 'fish'] as const) {
  if (!has(shell) && process.platform !== 'win32' && process.env.CI === 'true') {
    describe(`documented ${shell} completion setup`, () => {
      it(`requires ${shell} in CI`, () => {
        throw new Error(`${shell} is not installed but CI=true: documented setup tests cannot be skipped`);
      });
    });
  }
}

(has('zsh') ? describe : describe.skip)('documented zsh completion setup', () => {
  let home: string;
  let installed: string;
  let zsh: ZshSession;

  beforeAll(async () => {
    home = realDir(mkdtempSync(join(tmpdir(), 'codemie-zsh-setup-')));
    // docs/SHELL-COMPLETIONS.md:50 - save as ~/.zsh/completions/_codemie via a .tmp file and mv.
    installed = installCompletion(home, 'zsh', join(home, '.zsh', 'completions', '_codemie'));
    // docs/SHELL-COMPLETIONS.md:56 - the ~/.zshrc lines, nothing else: the script is never sourced by hand.
    writeFileSync(join(home, '.zshrc'), 'fpath=(~/.zsh/completions $fpath)\nautoload -Uz compinit && compinit\n');
    zsh = await startZsh({ name: 'codemie', cwd: home, mode: 'zshrc', home });
  }, 60000);

  afterAll(() => {
    zsh?.close();
    if (home) rmSync(home, { recursive: true, force: true });
  });

  // @case add-bash-zsh-and-fish_TC_004
  it('installs the generated script with its header at ~/.zsh/completions/_codemie', () => {
    // Grounding: src/cli/completion/zsh.ts:91-92 (#compdef line, then the generated-by header).
    const lines = installed.split('\n');
    expect(lines[0]).toBe('#compdef codemie');
    expect(lines[1]).toBe(`# codemie completion zsh — generated by codemie v${VERSION}`);
  });

  // @case add-bash-zsh-and-fish_TC_004
  it('a new shell registers _codemie from fpath and completes codemie <Tab> and codemie --<Tab>', async () => {
    expect(await zsh.expr('$_comps[codemie]')).toBe('_codemie');
    expect(await zsh.complete('codemie ')).toEqual(expect.arrayContaining(TOP_LEVEL));
    expect(await zsh.complete('codemie --')).toEqual(expect.arrayContaining(ROOT_OPTIONS));
  });
});

(has('fish') ? describe : describe.skip)('documented fish completion setup', () => {
  let home: string;
  let installed: string;

  beforeAll(() => {
    home = realDir(mkdtempSync(join(tmpdir(), 'codemie-fish-setup-')));
    // docs/SHELL-COMPLETIONS.md:69 - save as ~/.config/fish/completions/codemie.fish via a .tmp file and mv.
    installed = installCompletion(home, 'fish', join(home, '.config', 'fish', 'completions', 'codemie.fish'));
    return () => rmSync(home, { recursive: true, force: true });
  });

  /** A fresh fish whose default config dir is `<home>/.config/fish`; nothing is sourced by hand. */
  function fish(command: string): string {
    const env: NodeJS.ProcessEnv = { ...process.env, HOME: home };
    delete env.XDG_CONFIG_HOME;
    delete env.XDG_DATA_HOME;
    delete env.XDG_CACHE_HOME;
    const r = spawnSync('fish', ['-c', command], { cwd: home, env, encoding: 'utf8' });
    expect(r.status, r.stderr).toBe(0);
    return r.stdout;
  }
  const complete = (line: string): string[] =>
    fish(`complete -C '${line}'`)
      .split('\n')
      .filter(l => l !== '')
      .map(l => l.split('\t')[0]);

  // @case add-bash-zsh-and-fish_TC_004
  it('installs the generated script with its header at ~/.config/fish/completions/codemie.fish', () => {
    // Grounding: src/cli/completion/fish.ts:89 (first line is the generated-by header).
    expect(installed.split('\n')[0]).toBe(`# codemie completion fish — generated by codemie v${VERSION}`);
  });

  // @case add-bash-zsh-and-fish_TC_004
  it('a new shell autoloads the file and completes codemie <Tab> and codemie --<Tab>', () => {
    // Grounding: src/cli/completion/fish.ts:52 (walker function __codemie_state), loaded only on first completion.
    expect(fish("functions -q __codemie_state; echo $status; complete -C 'codemie ' >/dev/null; functions -q __codemie_state; echo $status").trim().split('\n')).toEqual(['1', '0']);
    expect(complete('codemie ')).toEqual(expect.arrayContaining(TOP_LEVEL));
    expect(complete('codemie --')).toEqual(expect.arrayContaining(ROOT_OPTIONS));
  });
});
