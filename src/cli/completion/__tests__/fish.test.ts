import { describe, it, expect } from 'vitest';
import { buildModel } from '../tree.js';
import { emitFish } from '../fish.js';
import { buildFixtureRoot } from '../../../../tests/helpers/completion-fixtures.js';

describe('emitFish', () => {
  const out = emitFish(buildModel(buildFixtureRoot()), '9.9.9');

  it('starts with the generated header including the version', () => {
    expect(out.split('\n')[0]).toBe('# codemie completion fish — generated by codemie v9.9.9');
  });

  it('registers completions for the root name only', () => {
    expect(out).toMatch(/complete -c tool /);
    expect(out).not.toMatch(/complete -c (?!tool\b)/);
  });

  it('never mentions hidden names', () => {
    expect(out).not.toMatch(/internal|--secret|\bsecret\b|\bzz\b/);
  });

  it('matches the snapshot', () => {
    expect(out).toMatchSnapshot();
  });
});
