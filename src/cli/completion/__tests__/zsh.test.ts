import { describe, it, expect } from 'vitest';
import { buildModel } from '../tree.js';
import { emitZsh } from '../zsh.js';
import { buildFixtureRoot } from '../../../../tests/helpers/completion-fixtures.js';

describe('emitZsh', () => {
  const out = emitZsh(buildModel(buildFixtureRoot()), '9.9.9');
  const lines = out.split('\n');

  it('starts with #compdef <root> then the generated header including the version', () => {
    expect(lines[0]).toBe('#compdef tool');
    expect(lines[1]).toBe('# codemie completion zsh — generated by codemie v9.9.9');
  });

  it('supports both autoload (fpath) and direct source', () => {
    expect(out).toMatch(/funcstack\[1\]/);
    expect(out).toMatch(/compdef _tool tool/);
    expect(out).toMatch(/_describe/);
  });

  it('alias shows the same description as its command', () => {
    const desc = (n: string): string | undefined => out.match(new RegExp(`'${n}:([^']*(?:'\\\\''[^']*)*)'`))?.[1];
    expect(desc('list')).toBeTruthy();
    expect(desc('ls')).toBe(desc('list'));
  });

  it('never mentions hidden names', () => {
    expect(out).not.toMatch(/internal|--secret|\bsecret\b|\bzz\b/);
  });

  it('matches the snapshot', () => {
    expect(out).toMatchSnapshot();
  });
});
