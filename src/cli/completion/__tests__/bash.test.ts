import { describe, it, expect } from 'vitest';
import { buildModel } from '../tree.js';
import { emitBash } from '../bash.js';
import { buildFixtureRoot } from '../../../../tests/helpers/completion-fixtures.js';

describe('emitBash', () => {
  const out = emitBash(buildModel(buildFixtureRoot()), '9.9.9');

  it('starts with the generated header including the version', () => {
    expect(out.split('\n')[0]).toBe('# codemie completion bash — generated by codemie v9.9.9');
  });

  it('avoids constructs missing from bash 3.2', () => {
    expect(out).not.toMatch(/mapfile|readarray|declare -A|bash-completion|_init_completion/);
  });

  it('registers the completion function derived from the root name', () => {
    expect(out).toMatch(/complete -F _tool tool\s*$/);
  });

  it('never mentions hidden names', () => {
    expect(out).not.toMatch(/internal|--secret|\bzz\b/);
  });

  it('matches the snapshot', () => {
    expect(out).toMatchSnapshot();
  });
});
