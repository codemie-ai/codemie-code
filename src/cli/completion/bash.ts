import { escapeBash } from './escape.js';
import { effectiveOptions } from './tree.js';
import type { NodeModel, OptionModel } from './tree.js';

/**
 * Bash completion emitter. Targets bash 3.2+: only `case` tables and
 * `compgen -W`; no bash-completion dependency, no associative arrays.
 * Bash offers names only, so descriptions are intentionally ignored.
 */

interface FlatNode {
  id: number;
  node: NodeModel;
}

function flatten(root: NodeModel): FlatNode[] {
  const out: FlatNode[] = [];
  const walk = (node: NodeModel): void => {
    out.push({ id: out.length, node });
    node.subs.forEach(walk);
  };
  walk(root);
  return out;
}

const q = (s: string): string => `'${escapeBash(s)}'`;

/** Single-quoted newline-separated list (escapeBash would collapse raw newlines). */
const qList = (items: string[]): string => `'${items.map(escapeBash).join('\n')}'`;

function optionNames(opt: OptionModel): string[] {
  return [opt.long, opt.short].filter((n): n is string => !!n);
}

/** What follows a required-value option: c = choices, f = files, n = nothing. */
function valueMode(opt: OptionModel): 'c' | 'f' | 'n' {
  if (opt.choices.length > 0) return 'c';
  return opt.valueKind === 'path' ? 'f' : 'n';
}

function functionName(name: string): string {
  return `_${name.replace(/[^A-Za-z0-9_]/g, '_')}`;
}

export function emitBash(model: NodeModel, version: string): string {
  const flat = flatten(model);
  const fn = functionName(model.name);
  const idOf = new Map<NodeModel, number>(flat.map(f => [f.node, f.id]));

  const edges: string[] = [];
  const optionCases: string[] = [];
  const wordCases: string[] = [];

  for (const { id, node } of flat) {
    for (const sub of node.subs) {
      const pats = [sub.name, ...sub.aliases].map(n => q(`${id}:${n}`)).join('|');
      edges.push(`      ${pats}) node=${idOf.get(sub)};;`);
    }

    const opts = effectiveOptions(node);
    for (const opt of opts) {
      if (opt.takesValue !== 'required') continue;
      const pats = optionNames(opt).map(n => q(`${id}:${n}`)).join('|');
      const mode = valueMode(opt);
      const vals = mode === 'c' ? ` vals=${qList(opt.choices)};` : '';
      optionCases.push(`        ${pats}) kind=${mode};${vals};`);
    }

    const words = new Set<string>();
    for (const sub of node.subs) [sub.name, ...sub.aliases].forEach(n => words.add(n));
    for (const opt of opts) optionNames(opt).forEach(n => words.add(n));
    if (node.subs.length === 0) node.positionalChoices.forEach(ch => words.add(ch));
    wordCases.push(`      ${id}) words=${qList([...words])};;`);
  }

  const lines = [
    `# codemie completion bash — generated by codemie v${version}`,
    `# Install: eval "$(${model.name} completion bash)"`,
    `${fn}() {`,
    '  local cur node w i kind vals vmode words',
    '  cur="${COMP_WORDS[COMP_CWORD]}"',
    '  node=0; vmode=; vals=; i=1',
    '  while [ "$i" -lt "$COMP_CWORD" ]; do',
    '    w="${COMP_WORDS[i]}"',
    '    case "$w" in',
    '      --) vmode=x; break;;',
    '      -*)',
    '        kind=',
    '        case "$node:$w" in',
    ...optionCases,
    '        esac',
    '        if [ -n "$kind" ]; then',
    '          if [ $((i + 1)) -ge "$COMP_CWORD" ]; then vmode="$kind"; break; fi',
    '          i=$((i + 1))',
    '        fi',
    '        ;;',
    '      *)',
    '        case "$node:$w" in',
    ...edges.map(e => `  ${e}`),
    '        esac',
    '        ;;',
    '    esac',
    '    i=$((i + 1))',
    '  done',
    '  local IFS=$\'\\n\'',
    '  case "$vmode" in',
    '    c) COMPREPLY=( $(compgen -W "$vals" -- "$cur") );;',
    '    f)',
    '      COMPREPLY=( $(compgen -f -- "$cur") )',
    '      type compopt >/dev/null 2>&1 && compopt -o filenames 2>/dev/null',
    '      ;;',
    '    n|x) COMPREPLY=();;',
    '    *)',
    '      case "$node" in',
    ...wordCases.map(w => `  ${w}`),
    '      esac',
    '      COMPREPLY=( $(compgen -W "$words" -- "$cur") )',
    '      ;;',
    '  esac',
    '  return 0',
    '}',
    /^[A-Za-z0-9_.-]+$/.test(model.name)
      ? `complete -F ${fn} ${model.name}`
      : `complete -F ${fn} ${q(model.name)}`,
    '',
  ];
  return lines.join('\n');
}
