import { escapeFish } from './escape.js';
import { effectiveOptions } from './tree.js';
import type { NodeModel, OptionModel } from './tree.js';

/**
 * Fish completion emitter. A generated `__<root>_state` function walks the
 * already-typed words and prints the current position: `<nodeId>` or, when the
 * previous word is a known option awaiting its value, `<nodeId>:<option>`.
 * Every `complete` rule is conditioned on that string. Files are disabled
 * (`-f`) except after path-valued options (`-F`).
 */

interface FlatNode {
  id: number;
  node: NodeModel;
}

function flatten(root: NodeModel): FlatNode[] {
  const out: FlatNode[] = [];
  const walk = (node: NodeModel): void => {
    out.push({ id: out.length, node });
    node.subs.forEach(walk);
  };
  walk(root);
  return out;
}

const q = (s: string): string => `'${escapeFish(s)}'`;

/** `complete -a` re-tokenizes its argument, so escape anything fish treats specially. */
const arg = (s: string): string => q(s.replace(/[^A-Za-z0-9_./:@%+=,-]/g, '\\$&'));

function optionNames(opt: OptionModel): string[] {
  return [opt.long, opt.short].filter((n): n is string => !!n);
}

function optionKey(id: number, opt: OptionModel): string {
  return `${id}:${optionNames(opt)[0]}`;
}

function optionFlags(opt: OptionModel): string {
  const parts: string[] = [];
  if (opt.long) parts.push(`-l ${q(opt.long.replace(/^--/, ''))}`);
  if (opt.short) parts.push(`-s ${q(opt.short.replace(/^-/, ''))}`);
  return parts.join(' ');
}

export function emitFish(model: NodeModel, version: string): string {
  const flat = flatten(model);
  const root = model.name;
  const ident = root.replace(/[^A-Za-z0-9_]/g, '_');
  const fn = `__${ident}_state`;
  const idOf = new Map<NodeModel, number>(flat.map(f => [f.node, f.id]));
  const at = (state: string): string => `-n ${q(`test (${fn}) = ${q(state)}`)}`;
  const c = `complete -c ${/^[A-Za-z0-9_.-]+$/.test(root) ? root : q(root)}`;

  const edges: string[] = [];
  const optionCases: string[] = [];
  const rules: string[] = [];

  for (const { id, node } of flat) {
    for (const sub of node.subs) {
      const pats = [sub.name, ...sub.aliases].map(n => q(`${id}:${n}`)).join(' ');
      edges.push(`        case ${pats}`, `          set node ${idOf.get(sub)}`);
      for (const n of [sub.name, ...sub.aliases]) {
        rules.push(`${c} ${at(String(id))} -a ${arg(n)} -d ${q(sub.description)}`);
      }
    }

    if (node.subs.length === 0) {
      for (const ch of node.positionalChoices) rules.push(`${c} ${at(String(id))} -f -a ${arg(ch)}`);
    }

    for (const opt of effectiveOptions(node)) {
      rules.push(`${c} ${at(String(id))} ${optionFlags(opt)} -d ${q(opt.description)}`);
      if (opt.takesValue !== 'required') continue;
      const key = optionKey(id, opt);
      const pats = optionNames(opt).map(n => q(`${id}:${n}`)).join(' ');
      optionCases.push(`          case ${pats}`, `            set key ${q(key)}`);
      if (opt.choices.length > 0) {
        for (const ch of opt.choices) rules.push(`${c} ${at(key)} -f -a ${arg(ch)}`);
      } else if (opt.valueKind === 'path') {
        rules.push(`${c} ${at(key)} -F`);
      }
    }
  }

  const lines = [
    `# codemie completion fish — generated by codemie v${version}`,
    `# Install: ${root} completion fish | source`,
    `function ${fn}`,
    '    set -l toks (commandline -opc)',
    '    set -e toks[1]',
    '    set -l node 0',
    '    set -l i 1',
    '    set -l n (count $toks)',
    '    while test $i -le $n',
    '        set -l w $toks[$i]',
    '        switch $w',
    "            case '--'",
    '                echo end',
    '                return',
    "            case '-*'",
    '                set -l key',
    '                switch "$node:$w"',
    ...optionCases.map(l => `    ${l}`),
    '                end',
    '                if test -n "$key"',
    '                    if test $i -ge $n',
    '                        echo $key',
    '                        return',
    '                    end',
    '                    set i (math $i + 1)',
    '                end',
    '            case \'*\'',
    '                switch "$node:$w"',
    ...edges.map(l => `    ${l}`),
    '                end',
    '        end',
    '        set i (math $i + 1)',
    '    end',
    '    echo $node',
    'end',
    `${c} -f`,
    ...rules,
    '',
  ];
  return lines.join('\n');
}
