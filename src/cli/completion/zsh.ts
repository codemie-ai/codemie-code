import { escapeBash, escapeZshDescribe } from './escape.js';
import { effectiveOptions } from './tree.js';
import type { NodeModel, OptionModel } from './tree.js';

/**
 * Zsh completion emitter. A generated `_<root>` function walks the typed words
 * (`$words[2,CURRENT-1]`) with `case` tables keyed `<nodeId>:<word>`, then offers
 * candidates with `_describe` (commands and options, with descriptions),
 * `compadd` (option choices) or `_files` (path options).
 *
 * The file works both autoloaded from fpath (`#compdef`, body runs as the
 * function body, so it ends by calling the function) and `source`d directly
 * (it then registers itself with `compdef`).
 */

interface FlatNode {
  id: number;
  node: NodeModel;
}

function flatten(root: NodeModel): FlatNode[] {
  const out: FlatNode[] = [];
  const walk = (node: NodeModel): void => {
    out.push({ id: out.length, node });
    node.subs.forEach(walk);
  };
  walk(root);
  return out;
}

const q = (s: string): string => `'${escapeBash(s)}'`;

/** Single-quoted `_describe` element: the name's `:` is escaped, the description follows the first bare `:`. */
function describeItem(name: string, description: string): string {
  const n = escapeBash(name).replace(/:/g, '\\:');
  const d = escapeZshDescribe(description);
  return d === '' ? `'${n}'` : `'${n}:${d}'`;
}

function optionNames(opt: OptionModel): string[] {
  return [opt.long, opt.short].filter((n): n is string => !!n);
}

/** What follows a required-value option: c = choices, f = files, n = nothing. */
function valueMode(opt: OptionModel): 'c' | 'f' | 'n' {
  if (opt.choices.length > 0) return 'c';
  return opt.valueKind === 'path' ? 'f' : 'n';
}

function functionName(name: string): string {
  return `_${name.replace(/[^A-Za-z0-9_]/g, '_')}`;
}

export function emitZsh(model: NodeModel, version: string): string {
  const flat = flatten(model);
  const fn = functionName(model.name);
  const idOf = new Map<NodeModel, number>(flat.map(f => [f.node, f.id]));

  const edges: string[] = [];
  const optionCases: string[] = [];
  const itemCases: string[] = [];

  for (const { id, node } of flat) {
    for (const sub of node.subs) {
      const pats = [sub.name, ...sub.aliases].map(n => q(`${id}:${n}`)).join('|');
      edges.push(`        ${pats}) node=${idOf.get(sub)};;`);
    }

    const opts = effectiveOptions(node);
    for (const opt of opts) {
      if (opt.takesValue !== 'required') continue;
      const pats = optionNames(opt).map(n => q(`${id}:${n}`)).join('|');
      const mode = valueMode(opt);
      const vals = mode === 'c' ? ` vals=(${opt.choices.map(q).join(' ')});` : '';
      optionCases.push(`          ${pats}) kind=${mode};${vals};`);
    }

    const cmds: string[] = [];
    for (const sub of node.subs) {
      for (const n of [sub.name, ...sub.aliases]) cmds.push(describeItem(n, sub.description));
    }
    const optItems: string[] = [];
    for (const opt of opts) {
      for (const n of optionNames(opt)) optItems.push(describeItem(n, opt.description));
    }
    const pos = node.subs.length === 0 ? node.positionalChoices.map(ch => describeItem(ch, '')) : [];
    itemCases.push(`    ${id}) cmds=(${cmds.join(' ')}); opts=(${optItems.join(' ')}); pos=(${pos.join(' ')});;`);
  }

  const lines = [
    `#compdef ${model.name}`,
    `# codemie completion zsh — generated by codemie v${version}`,
    `# Install: eval "$(${model.name} completion zsh)"  (or save as _${model.name} on your fpath)`,
    `${fn}() {`,
    '  local node w i kind vmode',
    '  local -a vals cmds opts pos',
    '  node=0; vmode=; vals=(); i=2',
    '  while (( i < CURRENT )); do',
    '    w="${words[i]}"',
    '    case "$w" in',
    '      --) vmode=x; break;;',
    '      -*)',
    '        kind=',
    '        case "$node:$w" in',
    ...optionCases,
    '        esac',
    '        if [[ -n "$kind" ]]; then',
    '          if (( i + 1 >= CURRENT )); then vmode="$kind"; break; fi',
    '          i=$(( i + 1 ))',
    '        fi',
    '        ;;',
    '      *)',
    '        case "$node:$w" in',
    ...edges,
    '        esac',
    '        ;;',
    '    esac',
    '    i=$(( i + 1 ))',
    '  done',
    '  case "$vmode" in',
    '    c) compadd -- "${vals[@]}"; return;;',
    '    f) _files; return;;',
    '    n|x) return 1;;',
    '  esac',
    '  case "$node" in',
    ...itemCases,
    '  esac',
    "  (( $#cmds )) && _describe 'command' cmds",
    "  (( $#opts )) && _describe 'option' opts",
    "  (( $#pos )) && _describe 'argument' pos",
    '  return 0',
    '}',
    `if [ "$funcstack[1]" = "${fn}" ]; then`,
    `  ${fn} "$@"`,
    'elif (( $+functions[compdef] )); then',
    `  compdef ${fn} ${/^[A-Za-z0-9_.-]+$/.test(model.name) ? model.name : q(model.name)}`,
    'fi',
    '',
  ];
  return lines.join('\n');
}
